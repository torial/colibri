fn test_kv16_round_is_ieee_half_rounding() {
	for v in kv16_vectors {
		got := math.f32_bits(kv16_round(math.f32_from_bits(v[0])))
		assert got == v[1], 'x=${v[0]:08x}: got ${got:08x}, want ${v[1]:08x}'
	}
}

fn test_kv16_keeps_a_nan_a_nan() {
	assert kv16_round(math.f32_from_bits(0x7fc00001)) != kv16_round(math.f32_from_bits(0x7fc00001))
}

fn test_softmax_and_rmsnorm_basics() {
	mut x := [f32(1), 2, 3]
	softmax_row(mut x, 3)
	assert x[0] + x[1] + x[2] > 0.9999 && x[0] + x[1] + x[2] < 1.0001
	assert x[2] > x[1] && x[1] > x[0]
	mut out := []f32{len: 2}
	rmsnorm_row(mut out, 0, [f32(3), 4], 0, [f32(1), 1], 2, 0)
	// rms = sqrt((9+16)/2); 3/rms, 4/rms
	assert out[0] > 0.848 && out[0] < 0.849 && out[1] > 1.131 && out[1] < 1.132
}

fn test_rejects_out_of_range_config() {
	d := os_tmp('olmoe_cfg')
	write_cfg(d, '{"hidden_size":8,"num_hidden_layers":1,"num_attention_heads":2,"num_key_value_heads":2,"num_experts":4,"num_experts_per_tok":9,"intermediate_size":4,"vocab_size":10}')
	if _ := load_cfg(d) {
		assert false // topk > experts
	}
	write_cfg(d, '{"hidden_size":8,"num_hidden_layers":1}')
	if _ := load_cfg(d) {
		assert false // a missing key
	}
	write_cfg(d, '{"hidden_size":8,"num_hidden_layers":1,"num_attention_heads":2,"num_key_value_heads":2,"num_experts":4,"num_experts_per_tok":2,"intermediate_size":4,"vocab_size":10,"norm_topk_prob":true,"rope_theta":500000}')
	c := load_cfg(d)!
	assert c.head_dim == 4 && c.norm_topk && c.theta == 500000 && c.eps == f32(1e-5)
}

fn os_tmp(tag string) string {
	d := os.join_path(os.vtmp_dir(), '${tag}_${os.getpid()}')
	os.mkdir_all(d) or { panic(err) }
	return d
}

fn write_cfg(d string, text string) {
	os.write_file('${d}/config.json', text) or { panic(err) }
}
