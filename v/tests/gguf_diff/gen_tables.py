#!/usr/bin/env python3
"""Generates the data tables of the V gguf / safetensors ports from the C headers, so no entry is typed by hand:
gguf/types.v (ggml type ids, block sizes) from c/ggml_quants.h, safetensors/st_gguf_maps.v (checkpoint name maps)
from c/st_gguf.h.   usage: gen_tables.py   (run from v/)"""
import re, os
here = os.path.dirname(os.path.abspath(__file__)); c = os.path.join(here, '..', '..', '..', 'c')
q = open(os.path.join(c, 'ggml_quants.h')).read()
enum = re.search(r'enum \{\s*GQ_F32 = 0,(.*?)\};', q, re.S).group(0)
ids = {m.group(1): int(m.group(2)) for m in re.finditer(r'(GQ_[A-Z0-9_]+) = (\d+)', enum)}
tmax = ids.pop('GQ_TYPE_MAX')
rows = {}
for m in re.finditer(r'\[(GQ_[A-Z0-9_]+)\]\s*=\s*\{ "([A-Za-z0-9_]+)",\s*(\d+),\s*(\d+),\s*(\d)', q):
    rows[m.group(1)] = (m.group(2), int(m.group(3)), int(m.group(4)), int(m.group(5)))
by_id = {ids[k]: v for k, v in rows.items()}
r16 = re.search(r'static inline int gq_r16_base.*?base\[\] = \{(.*?)\};', q, re.S).group(1)
r16 = [x.strip() for x in r16.split(',')]
gb = [int(x) for x in re.search(r'int16_t gb\[\] = \{(.*?)\};', q, re.S).group(1).split(',')]
names = re.search(r'static const char \*r16\[\] = \{(.*?)\};', q, re.S).group(1)
names = re.findall(r'"([^"]+)"', names)
out = ['module gguf', '', '// GENERATED by tests/gguf_diff/gen_tables.py from c/ggml_quants.h -- do not edit.', '',
       'pub struct GqType {', 'pub:', '\tname      string', '\tblck      int', '\tbytes     int', '\tsupported bool', '}', '', 'pub const gq_type_max = %d' % tmax, '']
for k, v in sorted(ids.items(), key=lambda kv: kv[1]):
    out.append('pub const %s = %d' % (k.lower(), v))
out += ['', 'pub const gq_types = [']
for i in range(tmax):
    n, b, by, s = by_id.get(i, ('', 0, 0, 0))
    out.append("\tGqType{'%s', %d, %d, %s}," % (n, b, by, 'true' if s else 'false'))
out += [']', '', 'pub const gq_r16_first = 64', 'pub const gq_r16_end = %d' % (64 + len(r16)), '',
        'const r16_base = [%s]' % ', '.join(x.lower() for x in r16), 'const r16_group_bytes = [%s]' % ', '.join(map(str, gb)),
        'const r16_names = [%s]' % ', '.join("'%s'" % n for n in names), '']
open(os.path.join(here, '..', '..', 'gguf', 'types.v'), 'w').write('\n'.join(out))

s = open(os.path.join(c, 'st_gguf.h')).read()
v = ['module safetensors', '', '// GENERATED by tests/gguf_diff/gen_tables.py from c/st_gguf.h -- do not edit.', '',
     'struct GgName {', '\tgg string', '\thf string', '}', '', 'struct GgMap {', '\tarch       string', '\tlayer_fmt  string', '\tglobals    []GgName', '\tlayer      []GgName', '}', '']
for m in re.finditer(r'static const st_gg_name (st_gg_\w+)\[\] = \{(.*?)\n\s*\{NULL, NULL\}\};', s, re.S):
    body = m.group(2)
    ents = re.findall(r'\{"([^"]*)",\s*"([^"]*)"\}', body)
    v.append('const %s = [' % m.group(1))
    for g, h in ents: v.append("\tGgName{'%s', '%s'}," % (g, h))
    v.append(']'); v.append('')
v.append('fn gg_maps() []GgMap {'); v.append('\treturn [')
for m in re.finditer(r'\{"([^"]+)", "([^"]+)", (st_gg_\w+), (st_gg_\w+)\}', s):
    v.append("\t\tGgMap{'%s', '%s', %s, %s}," % (m.group(1), m.group(2), m.group(3), m.group(4)))
v += ['\t]', '}', '']
open(os.path.join(here, '..', '..', 'safetensors', 'st_gguf_maps.v'), 'w').write('\n'.join(v))
print('types:', len(rows), 'of', tmax, '; maps tables:', len(re.findall(r'static const st_gg_name', s)))
